; ============================================================================
;  SIDEDAT.ASM - CPSIDE.DAT, the two 90-degree cockpit views, as a raw image.
;  Built exactly the way RESDAT.ASM builds CITY.DAT:
;      TASM SIDEDAT ; TLINK /t SIDEDAT  -> SIDEDAT.COM, copied to CPSIDE.DAT
;
;  WHY A SECOND FILE. CITY.DAT is read in one go with CX=0FFF0h - it can
;  never be more than 64K - and the front panel alone is 64000 of those
;  bytes. The side panels are RLE (about 24K each), so both fit in one page
;  of their own with room to spare, and neither the loader nor the far
;  memory map below scrseg has to move a paragraph. Moving that map is how
;  this project has broken itself twice; see the note in CITY.ASM.
;
;  Format - eight bytes of header, then the two streams:
;      'C','P'   magic
;      dw        of the LEFT stream, file-relative
;      dw        of the RIGHT stream
;      dw        0   (spare)
;  The streams themselves are described in CPSIDE.INC and decoded by
;  SIDEBMP in SYM.INC.
; ============================================================================
format binary as 'com'
        org 100h

        ; .8086 in the TASM source. FASM has no such directive - without this
        ; include it silently uses 386 jumps when a target is out of range.
        include '..\..\..\ENGINE\E_8086.INC'
SBASE:
        db 'C','P'
        dw CPLIMG-SBASE
        dw CPRIMG-SBASE
        dw 0

        include 'CPSIDE.INC'   ; generated by TOOLS\Panel2Inc

                                ; refuses the image outright

; ============================================================================
;  TURN.ASM - Lesson 5. Sixty-five numbers, and what they are for.
;
;      FASM TURN.ASM TURN.COM
;
;      1  the wave     the table, drawn as what it is
;      2  the circle   the same numbers, used the other way
;      3  the vector   where the two of them come from
;      4  no multiply  the same ring again, with shifts and adds only
;
;  The table was made by MKSIN.C, which ran once on another machine and is
;  not part of this program at all. What IS here is sixty-five whole numbers
;  and the four lines of arithmetic that unfold them into a whole circle.
;
;  A CIRCLE HAS 256 STEPS. Not 360 - 360 is a human convention with no factor
;  of two in it worth having. With 256 an angle wraps with AND 255, which is
;  free, and the quarter is the bottom six bits, which is a mask rather than a
;  division. Every constant in here was chosen because it is a power of two.
;
;  AND SINE IS KEPT AS sin*256. One is 256, a half is 128. Multiply by a
;  radius and shift down eight, and you have a distance in pixels without ever
;  having written a number with a dot in it.
;
;  FRAME 4 IS THE POINT OF LESSON 4. Frames 2 and 3 reach for IMUL because it
;  reads well, and lesson 4 spent ten minutes on why that instruction costs
;  more than a hundred clocks on an 8086. So frame 4 does the same arithmetic
;  with shifts and adds, draws its ring in white on top of the multiplied one
;  in red, and puts a red strip along the top of the screen if a single point
;  of the sixty-four comes out different. The strip stays black.
;
;  Owlos - legacy software modernization - https://owlos.sk
; ============================================================================
format binary as 'com'
        org  100h

VGA     = 0A000h                ; the graphics card's own memory
W       = 320                   ; mode 13h: 320 across
H       = 200                   ;           200 down
CX_     = 160                   ; the middle of the screen, across
CY_     = 100                   ;                           down
RAD     = 70                    ; the ring's radius, in pixels

        jmp  Boot

include 'SINT.INC'              ; the 65 numbers, generated by MKSIN.C

ang     dw 0                    ; the angle we are working on, 0..255
ptx     dw 0                    ; the pixel Px is to plot: across
pty     dw 0                    ;                          down
qx      dw 0                    ; frame 4: the same point, worked out
qy      dw 0                    ;   with shifts instead of a multiply
diff    dw 0                    ; frame 4: how many of the 64 disagreed
col     db 0                    ; the colour Px is to use, 0..255

; --- AND --------------------------------------------------------------- new
;  does    bitwise AND, one bit at a time: dst = dst AND src. A 0 in the
;          mask forces that bit to 0; a 1 leaves the bit alone.
;  flags   CF and OF cleared, ZF SF PF set from the result. We use none.
;  touches the destination only - a register or a memory word.
;  here    AND with 2^n-1 IS the remainder of a division by 2^n, and it
;          costs 3 clocks where DIV costs 160. 255 is 11111111b, so it
;          keeps the low eight bits: any angle at all lands in 0..255.
;  trap    only works as a remainder when the divisor is a power of two.
; ---------------------------------------------------------------------------

; --- SHR --------------------------------------------------------------- new
;  does    shift right, zeros in at the top. SHR by n is a divide by 2^n
;          for UNSIGNED numbers.
;  flags   CF gets the last bit shifted out - the remainder, if you want it.
;  touches the destination. The count is either the literal 1, or CL.
;  trap    THE 8086 HAS NO "SHR BX, 6". The count must be 1 or CL, which is
;          why CL is loaded first. Write the immediate and FASM will happily
;          assemble a 186 instruction that this machine does not have.
;  trap    SHR on a NEGATIVE number is not a divide. See SAR below.
; ---------------------------------------------------------------------------

; --- NEG --------------------------------------------------------------- new
;  does    dst = 0 - dst. Two's complement: flip every bit and add one.
;  flags   CF set unless the operand was 0; SF and ZF from the result.
;  trap    NEG of -32768 is -32768. There is no +32768 in 16 bits, and the
;          instruction sets OF to say so. Nothing here goes near it: the
;          largest thing we negate is 256.
; ---------------------------------------------------------------------------

; ---- sine, out of the quarter table ----------------------------------------
;  in:  AX = any angle at all
;  out: AX = sin(angle) * 256, from -256 to +256
;  eats BX, CX, DX, SI
;
;  The table holds one quarter. The second is the same numbers read backwards,
;  the third is the first negated, the fourth is the second negated - so
;  sixty-five words cover the whole circle and nothing is stored twice.
SINQ:   and  ax, 255            ; 255 = 11111111b. Keep 8 bits = angle mod 256.
        mov  bx, ax             ; a copy: one of them becomes the quarter,
        mov  cl, 6              ;  the other the distance into it. 6 because
        shr  bx, cl             ;  2^6 = 64, so BX = angle/64 = the quarter 0..3
        and  ax, 63             ; 63 = 111111b. AX = angle mod 64 = 0..63
        cmp  bx, 1              ; quarter 1 runs from the top of the table
        je   .back              ;  back down to the bottom...
        cmp  bx, 3              ; ...and so does quarter 3
        je   .back
        jmp  .have              ; quarters 0 and 2 read it forwards
.back:  mov  dx, 64             ; read it backwards: index = 64 - index
        sub  dx, ax
        mov  ax, dx
.have:  add  ax, ax             ; *2: the table holds WORDS, so entry n is
        mov  si, ax             ;  at byte 2n. Adding to itself beats SHL by
        mov  ax, [SINT+si]      ;  a clock and says the same thing.
        cmp  bx, 2              ; quarters 0 and 1 are the top half of the
        jb   .done              ;  circle - the sine there is positive
        neg  ax                 ; quarters 2 and 3 are below the axis
.done:  ret

; --- MUL --------------------------------------------------------------- new
;  does    UNSIGNED multiply. One operand is always AX and you do not write
;          it: MUL CX means DX:AX = AX * CX. The answer is 32 bits wide
;          because two 16-bit numbers can need 32.
;  flags   CF and OF set when DX is not zero - i.e. the answer did not fit
;          in AX alone. That is the only warning you get.
;  touches AX and DX, always, whether you wanted DX touched or not.
;  cost    118 to 133 clocks on an 8086. ADD is 3. That is lesson 4.
;  trap    MUL treats the bits as unsigned. -1 (0FFFFh) is 65535 to it.
;          For anything that can be negative, use IMUL.
; ---------------------------------------------------------------------------

; ---- one pixel, if it is on the screen -------------------------------------
;  in:  ptx, pty, col
;  The screen is one long run of 64000 bytes, so the address of a pixel is
;  y*320 + x. That multiply is the only one in the routine, and frame 4
;  shows it going away.
Px:     mov  ax, [pty]          ; the row
        cmp  ax, 0
        jl   .out               ; above the screen - drop it
        cmp  ax, H
        jge  .out               ; below it - drop it
        mov  bx, [ptx]          ; the column
        cmp  bx, 0
        jl   .out
        cmp  bx, W
        jge  .out
        mov  cx, W              ; 320 bytes to a row
        mul  cx                 ; DX:AX = y * 320. Max 199*320 = 63680, so
        add  ax, bx             ;  DX comes back 0 and AX is the whole answer
        mov  di, ax             ; DI = the offset into the card's memory
        mov  al, [col]
        stosb                   ; ES:DI <- AL, then DI = DI + 1 (CLD is set)
.out:   ret

; --- SHL --------------------------------------------------------------- new
;  does    shift left, zeros in at the bottom. SHL by n multiplies by 2^n.
;  flags   CF gets the last bit shifted out.
;  touches the destination. Count is 1 or CL, same 8086 rule as SHR.
;  here    SHL IS SIGN-BLIND AND STILL CORRECT. -100 shifted left 6 is
;          -6400, because two's complement multiplication by a power of two
;          is the same bit pattern either way. Only the DIVIDE direction
;          needs to know about the sign, which is what SAR is for.
;  trap    it is correct only while the answer FITS. Shift a bit off the
;          top and it is gone; CF is the one warning.
; ---------------------------------------------------------------------------

; ---- AX = AX * 70, and not a MUL in sight ----------------------------------
;  in:  AX = the sine, -256..+256
;  out: AX = AX * 70
;  eats BX, CL, DX
;
;  70 in binary is 1000110b - three bits set, at 64, 4 and 2. So
;
;      n * 70  =  n*64 + n*4 + n*2
;
;  which is three shifts and two adds: about 30 clocks against IMUL's 128.
;  It is EXACT. Nothing is rounded, nothing is approximated - it is the same
;  answer the multiplier would have given, which is the whole point of
;  frame 4 drawing one ring on top of the other.
;
;  Worked, for sin = 256 (the largest there is):
;      256*64 = 16384
;      256*4  =  1024      16384 + 1024 = 17408
;      256*2  =   512      17408 +  512 = 17920   = 256 * 70
Mul70:  mov  bx, ax             ; BX keeps the original n
        mov  cl, 6              ; 2^6 = 64
        shl  ax, cl             ; AX = n * 64
        mov  dx, bx
        shl  dx, 1              ; DX = n * 2
        add  ax, dx             ; AX = n * 66
        shl  dx, 1              ; DX = n * 4
        add  ax, dx             ; AX = n * 70
        ret

; ---- one pixel, with the address built by shifts too -----------------------
;  Same as Px in every line but three. The screen is 320 bytes to a row and
;
;      320 = 256 + 64  =  100000000b + 1000000b
;
;  so y*320 is (y shifted left 8) plus (y shifted left 6), and the last
;  multiply in the program is gone. y is at most 199, so y*320 is at most
;  63680 - it fits in 16 bits with 1855 to spare.
PxS:    mov  ax, [pty]
        cmp  ax, 0
        jl   .out
        cmp  ax, H
        jge  .out
        mov  bx, [ptx]
        cmp  bx, 0
        jl   .out
        cmp  bx, W
        jge  .out
        mov  dx, ax             ; DX keeps the row
        mov  cl, 8
        shl  ax, cl             ; AX = y * 256
        mov  cl, 6
        shl  dx, cl             ; DX = y * 64
        add  ax, dx             ; AX = y * 320. No MUL, and DX is not eaten
        add  ax, bx             ;  by the instruction the way MUL eats it
        mov  di, ax
        mov  al, [col]
        stosb
.out:   ret

Key:    mov  ah, 0              ; BIOS: wait for a keystroke
        int  16h
        ret

Clear:  xor  di, di             ; DI = 0, and shorter than MOV DI,0
        xor  ax, ax             ; the colour to fill with: 0, black
        mov  cx, W*H/2          ; 32000 WORDS, because STOSW writes two
        rep  stosw              ;  bytes a time - half the loop, same 64000
        ret

Boot:   cld                     ; DI counts UP in every STOS below
        mov  ax, 0013h          ; BIOS: mode 13h, 320x200, 256 colours
        int  10h
        mov  ax, VGA
        mov  es, ax             ; ES = A000h, so ES:DI addresses the screen

; --- SAR --------------------------------------------------------------- new
;  does    shift right ARITHMETIC. The top bit is copied into itself instead
;          of a zero coming in, so the sign survives. SAR by n is a divide
;          by 2^n for SIGNED numbers.
;  flags   CF gets the last bit shifted out. OF cleared.
;  touches the destination. Count is 1 or CL - the 8086 rule again.
;  why     take -8 = 11111000b (as a byte, for legibility).
;              SAR 1 -> 11111100b = -4    correct
;              SHR 1 -> 01111100b = +124  a large positive number
;          Half our sines are negative, so SHR here would fling those points
;          to the far side of the screen. It is a one-letter difference and
;          it is not a style choice.
;  trap    SAR rounds DOWN, towards minus infinity, not towards zero.
;          -1 SAR 1 is -1, not 0. Errors of one pixel come from here.
; ---------------------------------------------------------------------------

; ---- 1. the table, drawn as what it is -------------------------------------
; One pixel per entry, straight across the screen: the angle is the x, the
; sine is the y. If the sixty-five numbers are right, this is a sine wave -
; and if they are not, it will be obvious from here.
        mov  byte [col], 44     ; a mid red
        mov  word [ang], 0
        mov  cx, 256            ; one dot per step of the whole circle
.wave:  push cx                 ; SINQ eats CX, so the counter goes on the
        mov  ax, [ang]          ;  stack for the length of the body
        add  ax, 32             ; 32 pixels in from the left edge
        mov  [ptx], ax          ; the angle, across

        mov  ax, [ang]
        call SINQ               ; AX = sin * 256, so -256..+256
        mov  cl, 2              ; the shift count. 2, so 2^2 = 4
        sar  ax, cl             ; /4: -64..+64, which 200 rows can hold. SAR
        neg  ax                 ; screen y grows DOWN, arithmetic y grows UP
        add  ax, CY_            ; and 0 is the middle row, not the top one
        mov  [pty], ax          ; the sine, down
        call Px

        inc  word [ang]         ; the next step of the 256
        pop  cx
        loop .wave              ; LOOP = DEC CX, jump if not zero

        mov  di, CY_*W + 32     ; the axis: row 100, 32 in
        mov  cx, 256
        mov  al, 8              ; dark grey
        rep  stosb
        call Key

; ---- 2. the same numbers, used the other way -------------------------------
; Now instead of putting the sine on the screen, put it on a radius. x is the
; cosine of the angle times the radius, y is the sine - and sixty-four of them
; make a ring. Same table, same routine, different question.

; --- IMUL -------------------------------------------------------------- new
;  does    SIGNED multiply. IMUL BX is DX:AX = AX * BX, with both read as
;          signed 16-bit numbers.
;  flags   CF and OF set when DX is NOT just the sign spilling out of AX -
;          i.e. when the answer needed more than 16 bits.
;  touches AX and DX. DX is destroyed whether you look at it or not.
;  cost    128 to 154 clocks. Frame 4 does the same job in about 30.
;  here    sin*256 is at most 256, times a radius of 70 is 17920 - inside
;          32767, so DX comes back as sign only and AX holds the answer.
;          THE LIMIT: radius 127 gives 32512 and still fits. Radius 128
;          gives 32768, which is negative in 16 bits, and the ring turns
;          inside out. Everything here is built for a screen 200 tall, so
;          it never gets close - but that is where the edge is.
; ---------------------------------------------------------------------------
        call Clear
        mov  byte [col], 44
        mov  word [ang], 0
        mov  cx, 64             ; 64 points around the ring
.ring:  push cx
        mov  ax, [ang]
        add  ax, 64             ; cos(a) = sin(a + a quarter). 64 of 256 IS
        call SINQ               ;  a quarter turn. One addition, no cosine
        mov  bx, RAD            ;  table, no second routine.
        imul bx                 ; DX:AX = sin*256 * 70
        mov  cl, 8
        sar  ax, cl             ; /256 undoes the *256 the table carries.
        add  ax, CX_            ;  What is left is a distance in pixels.
        mov  [ptx], ax

        mov  ax, [ang]
        call SINQ               ; and the sine itself, for the y
        mov  bx, RAD
        imul bx
        mov  cl, 8
        sar  ax, cl
        add  ax, CY_
        mov  [pty], ax
        call Px

        add  word [ang], 4      ; 256/64 = 4 - one point every fourth step
        pop  cx
        loop .ring
        call Key

; ---- 3. where those two numbers come from ----------------------------------
; One angle, and the two sides of the triangle it stands on. The horizontal
; run is the cosine, the vertical run is the sine, and the dot is where they
; meet. Everything above is this, done over and over.
        call Clear
        mov  word [ang], 40     ; one angle, picked to look like something

        mov  ax, [ang]          ; work the point out once, both coordinates
        add  ax, 64
        call SINQ
        mov  bx, RAD
        imul bx
        mov  cl, 8
        sar  ax, cl
        add  ax, CX_
        mov  [ptx], ax
        mov  ax, [ang]
        call SINQ
        mov  bx, RAD
        imul bx
        mov  cl, 8
        sar  ax, cl
        add  ax, CY_
        mov  [pty], ax

        mov  di, CY_*W + CX_    ; the cosine: along the middle row, from
        mov  cx, [ptx]          ;  the centre out to the point's x
        sub  cx, CX_
        mov  al, 9              ; light blue
        rep  stosb

        mov  ax, CY_            ; the sine: straight down from there. The
        mov  bx, W              ;  address is row*320 + column again
        mul  bx
        add  ax, [ptx]
        mov  di, ax
        mov  cx, [pty]          ; as many rows as the sine is tall
        sub  cx, CY_
.down:  mov  byte [es:di], 14   ; yellow
        add  di, W              ; the pixel below is 320 bytes further on
        loop .down

        mov  byte [col], 15     ; white
        call Px                 ; and the corner where the two meet
        call Key

; ---- 4. the same ring, without a multiply ----------------------------------
; Lesson 4 argued that MUL and DIV are the expensive instructions and that
; shifts and adds will do. Frames 2 and 3 then used IMUL twice a point,
; because it reads well. So: the same sixty-four points, worked out both
; ways. The multiplied ring goes down first in red, the shifted ring goes on
; top of it in white, and every point that disagrees is counted. If the
; count is anything but zero the top of the screen turns red.
;
; It stays black. They are not close - they are the same number.
        call Clear
        mov  word [ang], 0
        mov  word [diff], 0
        mov  cx, 64
.free:  push cx

        mov  ax, [ang]          ; ---- x, the way frame 2 did it
        add  ax, 64
        call SINQ
        push ax                 ; the sine is needed twice - keep it
        mov  bx, RAD
        imul bx                 ; 128 clocks
        mov  cl, 8
        sar  ax, cl
        add  ax, CX_
        mov  [ptx], ax
        pop  ax                 ; ---- and the same x, the cheap way
        call Mul70              ; 30 clocks, same answer
        mov  cl, 8
        sar  ax, cl             ; the /256 is a shift in both versions -
        add  ax, CX_            ;  it always was. Only the * was costly.
        mov  [qx], ax
        mov  bx, [ptx]
        cmp  bx, [qx]           ; did the two agree on this coordinate?
        je   .okx
        inc  word [diff]        ; no - and the strip at the top will say so
.okx:
        mov  ax, [ang]          ; ---- y, both ways, exactly as above
        call SINQ
        push ax
        mov  bx, RAD
        imul bx
        mov  cl, 8
        sar  ax, cl
        add  ax, CY_
        mov  [pty], ax
        pop  ax
        call Mul70
        mov  cl, 8
        sar  ax, cl
        add  ax, CY_
        mov  [qy], ax
        mov  bx, [pty]
        cmp  bx, [qy]
        je   .oky
        inc  word [diff]
.oky:
        mov  byte [col], 44     ; the multiplied point, in red, first
        call Px
        mov  ax, [qx]           ; the shifted point, in white, on top of it
        mov  [ptx], ax
        mov  ax, [qy]
        mov  [pty], ax
        mov  byte [col], 15
        call PxS                ; and PxS - so this point reached the screen
                                ;  without a single MUL anywhere in its path
        add  word [ang], 4
        pop  cx

; --- LOOP, and where it stops working ---------------------------------- new
;  does    DEC CX, then jump if CX is not zero. One instruction for the
;          commonest loop there is, and it sets NO flags at all.
;  reach   the jump is ONE SIGNED BYTE: -128 to +127 from the instruction
;          after it. There is no long form. Neither has JNZ on an 8086.
;  here    this body is about 140 bytes - doing the same work twice makes
;          it so - and LOOP cannot see that far. The assembler says
;          "relative jump out of range" and stops, which is the good case.
;  fix     step the counter by hand and let an UNCONDITIONAL jump do the
;          reaching: JMP is +/-32K. Invert the test so the short jump goes
;          FORWARDS, over the top of it, where 128 bytes is plenty.
; ---------------------------------------------------------------------------
        dec  cx                 ; what LOOP would have done...
        jz   .done4             ; ...and what it could not reach
        jmp  .free
.done4:
        cmp  word [diff], 0     ; the alarm. Zero and nothing is drawn.
        je   .same
        xor  di, di             ; anything else: a red strip along row 0
        mov  cx, W
        mov  al, 40
        rep  stosb
.same:  call Key

Bye:    mov  ax, 0003h          ; back to text, 80x25
        int  10h
        mov  ax, 4C00h          ; and hand the machine back to DOS
        int  21h
